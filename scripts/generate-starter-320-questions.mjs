function rotateOptions(options, shift) {
  const normalized = options.map((option, index) => `${String.fromCharCode(65 + index)}.${option.replace(/^[A-D]\./, '')}`);
  const offset = shift % normalized.length;
  return [...normalized.slice(offset), ...normalized.slice(0, offset)].map((option, index) => {
    const text = option.replace(/^[A-D]\./, '');
    return `${String.fromCharCode(65 + index)}.${text}`;
  });
}

function rotateAnswer(answer, shift) {
  const originalIndex = answer.charCodeAt(0) - 65;
  const offset = shift % 4;
  return String.fromCharCode(65 + ((originalIndex - offset + 4) % 4));
}

function csvEscape(value) {
  const text = String(value);
  return /[",\n\r]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}
